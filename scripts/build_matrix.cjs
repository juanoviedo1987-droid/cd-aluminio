const lines = rawData.split('\n');
const priceMap = {}; // key: `${ancho}x${alto}` => number
const anchosSet = new Set();
const altosSet = new Set();

for (const line of lines) {
  const trimmed = line.trim();
  if (!trimmed) continue;
  // Match e.g. "600x400  $3,920" or "600 x 600  $4,620" or "1200X1600 $11,060"
  const match = trimmed.match(/^(\d+)\s*[xX]\s*(\d+)\s+[\$]?\s*([0-9.,]+)$/);
  if (match) {
    const ancho = parseInt(match[1], 10);
    const alto = parseInt(match[2], 10);
    const precio = parseInt(match[3].replace(/[.,]/g, ''), 10);
    priceMap[`${ancho}x${alto}`] = precio;
    anchosSet.add(ancho);
    altosSet.add(alto);
  }
}

const anchos = Array.from(anchosSet).sort((a, b) => a - b);
const altos = Array.from(altosSet).sort((a, b) => a - b);

console.log(`Parsed ${Object.keys(priceMap).length} combinations.`);
console.log('Anchos:', anchos);
console.log('Altos:', altos);

// Let's create the grid CSV
const header = ['Alto (mm) / Ancho (mm)', ...anchos.map(a => `${a} mm`)];
const rows = [header];

for (const alto of altos) {
  const row = [`${alto} mm`];
  for (const ancho of anchos) {
    const key = `${ancho}x${alto}`;
    const precio = priceMap[key];
    row.push(precio !== undefined ? precio : '');
  }
  rows.push(row);
}

const fs = require('fs');
const csvContent = rows.map(r => r.join(',')).join('\n');
fs.writeFileSync('matriz_serie20.csv', csvContent, 'utf8');

// Also create a JSON mapping for direct embedding or fallback
fs.writeFileSync('matriz_serie20.json', JSON.stringify({ anchos, altos, priceMap }, null, 2), 'utf8');
console.log('Wrote matriz_serie20.csv and matriz_serie20.json successfully!');
